/**
 * Regenerate supabase/_run_all.sql — the whole SETUP concatenated in dependency
 * order so it can be pasted into the Supabase SQL Editor in one shot. Source of
 * truth is supabase/manifest.mjs; run `npm run db:bundle` after changing any SQL.
 *
 * The bundle contains the `setup` + `harden` phases (schema → … → chat → slug
 * hardening). Sample/tenant SEED data is intentionally excluded — a real project
 * shouldn't get demo rows; load it separately with `npm run db:apply -- --with-seed`
 * or by pasting seed.sql / seed-villas.sql.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { MANIFEST } from "../supabase/manifest.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SQL_DIR = resolve(__dirname, "../supabase");

const files = MANIFEST.filter((m) => m.phase === "setup" || m.phase === "harden");

const header = `-- =============================================================================
-- PoolOps Pro — FULL SETUP (all setup SQL concatenated in dependency order).
-- Paste this whole file into the Supabase SQL Editor and click Run.
--
-- GENERATED by scripts/build-run-all.mjs from supabase/manifest.mjs — do not edit
-- by hand; edit the individual files and re-run \`npm run db:bundle\`.
-- Generated ${new Date().toISOString()}.
--
-- Excludes SEED data (sample/tenant rows). To load it, run the seed files
-- separately or use \`npm run db:apply -- --with-seed\`.
-- Included, in order:
${files.map((m) => `--   ${String(m.file).padEnd(34)} ${m.desc}`).join("\n")}
-- =============================================================================
`;

const parts = files.map((m) => {
  const sql = readFileSync(resolve(SQL_DIR, m.file), "utf8").trimEnd();
  return `\n-- >>>>>>>>>>>>>>>>>>>> BEGIN ${m.file} >>>>>>>>>>>>>>>>>>>>\n\n${sql}\n\n-- <<<<<<<<<<<<<<<<<<<< END ${m.file} <<<<<<<<<<<<<<<<<<<<\n`;
});

const out = `${header}${parts.join("\n")}\n`;
const dest = resolve(SQL_DIR, "_run_all.sql");
writeFileSync(dest, out, "utf8");
console.log(`✅ Wrote ${dest}\n   ${files.length} files, ${out.split("\n").length} lines.`);
